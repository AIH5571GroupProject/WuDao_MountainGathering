  function translate(lang, key, vars) {
    var table = DICT[lang] || DICT.zh;
    var val = Object.prototype.hasOwnProperty.call(table, key) ? table[key] : DICT.zh[key];
    if (typeof val !== 'string') return val !== undefined ? val : key;
    if (!vars) return val;
    return val.replace(/\{(\w+)\}/g, function (_, k) {
      return Object.prototype.hasOwnProperty.call(vars, k) ? String(vars[k]) : '{' + k + '}';
    });
  }

